-- Reproducible EMP/DEPT educational schema for MySQL 8+
DROP DATABASE IF EXISTS business_people;
CREATE DATABASE business_people;
USE business_people;

CREATE TABLE dept (
    deptno INT PRIMARY KEY,
    dname VARCHAR(30) NOT NULL,
    loc VARCHAR(30) NOT NULL
);

CREATE TABLE emp (
    empno INT PRIMARY KEY,
    ename VARCHAR(30) NOT NULL,
    job VARCHAR(30) NOT NULL,
    mgr INT NULL,
    hiredate DATE NOT NULL,
    sal DECIMAL(10,2) NOT NULL,
    comm DECIMAL(10,2) NULL,
    deptno INT NULL,
    CONSTRAINT fk_emp_manager FOREIGN KEY (mgr) REFERENCES emp(empno),
    CONSTRAINT fk_emp_department FOREIGN KEY (deptno) REFERENCES dept(deptno)
);

